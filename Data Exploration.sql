-----------------------------------------
-- MAGNITUDE ANALYSIS
-----------------------------------------
-- Find Total customers by countries
SELECT 
	country, 
	COUNT(customer_key) 'Number'
FROM gold.dim_customers
GROUP BY country
ORDER BY 2 DESC;

-- Find Total Customers by gender
SELECT 
	gender, 
	COUNT(customer_key) 'total_customers'
FROM gold.dim_customers
GROUP BY gender
ORDER BY 2 DESC;

-- Find Total Product by category
SELECT 
	category, 
	COUNT(product_key) 'total_products'
FROM gold.dim_product
GROUP BY category
ORDER BY 2 DESC;

-- What is the average costs in each category
SELECT
	p.category, 
	AVG(product_cost) 'avg_price'
FROM gold.dim_product p
GROUP BY p.category
ORDER BY 2 DESC;

-- What is the total revenue generated for each category?
SELECT
	p.category, SUM(s.sales_amount) 'Total_Revenue'
FROM gold.dim_product p
RIGHT JOIN gold.fact_sales s
	ON p.product_key = s.product_key
GROUP BY p.category
ORDER BY 2 DESC;

-- Find the Total Revenue generated by each customer?
SELECT
	C.customer_key, 
	C.first_name,
	c.last_name,
	SUM(s.sales_amount) 'Total_Revenue'
FROM gold.dim_customers C
RIGHT JOIN gold.fact_sales s
	ON C.customer_key = s.product_key
GROUP BY C.customer_key, C.first_name, c.last_name
ORDER BY 2 DESC;

-- What is the distribution of sold items across countries?
SELECT
	c.country, 
	SUM(s.quantity) 'total_sold_items'
FROM gold.fact_sales s
LEFT JOIN gold.dim_customers c
	ON s.customer_key = c.customer_key
GROUP BY c.country
ORDER BY 2 DESC;


-----------------------------------------
-- RANKING ANALYSIS
-----------------------------------------
-- Which 5 products generate the highest revenue?
SELECT * 
FROM (
	SELECT
		p.product_name,
		SUM(s.sales_amount) AS total_revenue,
		RANK() OVER (ORDER BY SUM(sales_amount) DESC) AS ranking
	FROM gold.fact_sales s
	LEFT JOIN gold.dim_products p
		ON s.product_key = p.product_key
	GROUP BY p.product_name
) AS ranked_products
WHERE ranking <= 5;

-- What are the 5 worst-perfroming products in terms of sales?
SELECT TOP 5
	p.product_name,
	SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
	ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_revenue;

-- Find the top 10 customers who have generated the highest revenue
SELECT TOP 10
	c.customer_key,
	c.first_name,
	c.last_name,
	SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
	ON f.product_key = c.customer_key
GROUP BY 
	c.customer_key, c.first_name, c.last_name
ORDER BY total_revenue;

-- The 3 customers with the fewest orders placed
SELECT TOP 3
	c.customer_key,
	c.first_name,
	c.last_name,
	COUNT(f.order_number) AS order_count
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
	ON f.customer_key = c.customer_key
GROUP BY 
	c.customer_key, c.first_name, c.last_name
ORDER BY order_count ASC;
