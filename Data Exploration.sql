-----------------------------------------
-- DATE EXPLORATION
-----------------------------------------
-- Find the date of the first and last order
-- How many months of sales available (timespan by Date difference of earliest and oldest order)
SELECT 
	MIN(order_date) AS first_order, 
	MAX(order_date) AS last_order,
	DATEDIFF(month, MIN(order_date),MAX(order_date)) AS 'Timespan(months)'--timespan
FROM gold.fact_sales

-- Find youngest and oldest customer ages
SELECT
	MAX(birth_date) youngest_birthdate,
	DATEDIFF(year, MAX(birth_date), GETDATE()) youngest_age,
	MIN(birth_date) oldest_birthdate,
	DATEDIFF(year, MIN(birth_date), GETDATE()) oldest_age
FROM gold.dim_customers


